/** The multi-colour Google "G" (48 x 48 viewport). */
@Composable
fun GoogleG(modifier: Modifier = Modifier) {
    val parts = remember {
        GoogleParts.map { (data, color) -> PathParser().parsePathString(data).toPath() to color }
    }
    Canvas(modifier) {
        val factor = this.size.minDimension / 48f
        scale(factor, Offset.Zero) {
            parts.forEach { (path, color) -> drawPath(path, color) }
        }
    }
}
