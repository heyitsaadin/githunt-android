@Composable
fun PathIcon(
    pathData: String,
    tint: Color,
    modifier: Modifier = Modifier,
    iconSize: Dp = 24.dp,
    evenOdd: Boolean = false,
) {
    val path = remember(pathData, evenOdd) {
        PathParser().parsePathString(pathData).toPath().apply {
            if (evenOdd) fillType = PathFillType.EvenOdd
        }
    }
    Canvas(modifier.size(iconSize)) {
        val factor = this.size.minDimension / 24f
        scale(factor, Offset.Zero) {
            drawPath(path, tint)
        }
    }
}

